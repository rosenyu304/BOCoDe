"""Build ALL LCBench tables + the LCBench.py problem classes.

Extracts the seven tunable hyperparameters + final validation accuracy for each of
2000 configurations, for every LCBench dataset (35), into small CSVs in
``bocode/opt_problems/hpo/data/``, and (re)generates ``hpo/LCBench.py`` with one
problem class per dataset. One-time:

    curl -L https://ndownloader.figshare.com/files/21188598 -o data_2k_lw.zip
    unzip data_2k_lw.zip
    python tools/build_lcbench_tables.py --data /path/to/data_2k_lw.json

Note: LCBench stores num_layers=1 as JSON ``true`` (1 == True), so values are coerced
with float() (float(True) == 1.0).
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

import numpy as np

HP = [
    "batch_size",
    "learning_rate",
    "max_dropout",
    "max_units",
    "momentum",
    "num_layers",
    "weight_decay",
]

_MODULE_HEADER = '''"""LCBench benchmarks — discrete neural-network HPO pools (one per OpenML dataset).

Auto-generated by ``tools/build_lcbench_tables.py``. Each class tunes a funnel MLP's
seven hyperparameters (see :mod:`._lcbench_base`) on the named dataset, maximizing
final validation accuracy. Mixed-variable (batch_size, max_units, num_layers integer).

Sources:
L. Zimmer, M. Lindauer, F. Hutter. Auto-PyTorch: Multi-Fidelity MetaLearning for Efficient and Robust AutoDL. IEEE Transactions on Pattern Analysis and Machine Intelligence 43(9):3079-3090, 2021. https://github.com/automl/LCBench
"""

from __future__ import annotations

from ._lcbench_base import LCBenchProblem
'''


def _camel(name: str) -> str:
    parts = re.split(r"[^0-9a-zA-Z]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--data", required=True, help="path to data_2k_lw.json")
    args = ap.parse_args()

    data = json.load(open(args.data))
    root = Path(__file__).resolve().parent.parent
    out = root / "bocode/opt_problems/hpo/data"
    out.mkdir(parents=True, exist_ok=True)

    tables, classes = {}, []
    for ds in sorted(data):
        cfgs = data[ds]
        rows = [[float(cfgs[c]["config"][h]) for h in HP] for c in cfgs]
        accs = [[float(cfgs[c]["results"]["final_val_accuracy"])] for c in cfgs]
        key = ds.replace("-", "_").replace(".", "_")
        tables[key] = np.hstack([np.asarray(rows), np.asarray(accs)]).astype(np.float32)
        classes.append((f"LCBench{_camel(ds)}", key, ds))
    np.savez_compressed(out / "lcbench_data.npz", **tables)

    src = [_MODULE_HEADER]
    for cls, key, ds in classes:
        src.append(
            f"\n\nclass {cls}(LCBenchProblem):\n"
            f'    """LCBench MLP tuning on the {ds} dataset (7 hyperparameters)."""\n\n'
            f'    task_key = "{key}"\n'
        )
    (root / "bocode/opt_problems/hpo/LCBench.py").write_text("".join(src))
    print(f"wrote lcbench_data.npz + {len(classes)} LCBench classes")


if __name__ == "__main__":
    main()
